"""Built-in 3-band equalizer for PipeWire -- no Voicemeeter, no EasyEffects.

How it works
------------
When the user switches the EQ on, we start a small PipeWire "filter-chain" process
(`pipewire -c <generated conf>`) that creates a virtual output called "YTM Starcast EQ":
    apps -> [YTM Starcast EQ: bass shelf -> mid peak -> treble shelf] -> the real output
and make it the default output. The *real* output is chosen as the device that was the
default at that moment (or whichever the user selects in the app afterwards).

Safety properties (deliberate):
  * Nothing is created or changed until the user turns the EQ on. Off = exactly the stock setup.
  * Turning it off (or stopping the server) restores the previous default output.
  * The real device's own volume is never touched, so if the EQ process dies the audio falls
    back to the device at the level it already had -- no sudden loud output.
  * Independent of EasyEffects: it is a separate chain and can sit in front of any device.

Band changes are applied live with `pw-cli set-param` (no dropouts); if that ever fails the
chain is restarted with the new gains.
"""
import glob
import json
import os
import shutil
import subprocess
import threading
import time
from pathlib import Path

SINK_NAME = "pocketfader_eq"   # kept from the old name (Pocketfader): only the description below is shown to people
EQ_MIN, EQ_MAX = -12.0, 12.0
# band -> (biquad type, centre/corner Hz, Q). Names match the Voicemeeter-era API.
BANDS = {
    "bass": ("bq_lowshelf", 100.0, 0.7),
    "mid": ("bq_peaking", 1000.0, 0.7),
    "high": ("bq_highshelf", 8000.0, 0.7),
}
PRESETS = {
    "flat": {"bass": 0, "mid": 0, "high": 0},
    "bass-boost": {"bass": 6, "mid": 0, "high": 0},
    "vocal": {"bass": -2, "mid": 4, "high": 1},
    "treble-boost": {"bass": 0, "mid": 0, "high": 6},
    "loudness": {"bass": 5, "mid": -1, "high": 4},
}


def chain_conf(target, gains, description="YTM Starcast EQ"):
    """PipeWire config text for the filter-chain process."""
    nodes = ""
    for band, (label, freq, q) in BANDS.items():
        nodes += (f'                    {{ type = builtin name = {band} label = {label}\n'
                  f'                      control = {{ "Freq" = {freq} "Q" = {q} "Gain" = {float(gains.get(band, 0.0))} }} }}\n')
    names = list(BANDS)
    links = "".join(f'                    {{ output = "{a}:Out" input = "{b}:In" }}\n'
                    for a, b in zip(names, names[1:]))
    return f'''# Generated by YTM Starcast. Do not edit; it is rewritten whenever the EQ starts.
context.properties = {{ log.level = 1 }}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = "{description}"
            media.name = "{description}"
            filter.graph = {{
                nodes = [
{nodes}                ]
                links = [
{links}                ]
            }}
            audio.channels = 2
            audio.position = [ FL FR ]
            capture.props = {{
                node.name = "{SINK_NAME}"
                media.class = Audio/Sink
            }}
            playback.props = {{
                node.name = "{SINK_NAME}_out"
                node.passive = true
                node.dont-fallback = true
                target.object = "{target}"
            }}
        }}
    }}
]
'''


def module_present():
    dirs = [os.environ.get("PIPEWIRE_MODULE_DIR", "")] + glob.glob("/usr/lib*/pipewire-0.3") + \
        glob.glob("/usr/lib/*/pipewire-0.3") + glob.glob("/usr/local/lib*/pipewire-0.3")
    return any(d and os.path.exists(os.path.join(d, "libpipewire-module-filter-chain.so")) for d in dirs)


class BuiltinEQ:
    label = "Built-in EQ"
    capabilities = {"eq": True, "meter": False, "eq_toggle": True}
    actions = {}

    def __init__(self, runner, audio, store, conf_dir, pipewire="pipewire", pwcli="pw-cli", pwdump="pw-dump"):
        self.r, self.audio, self.store = runner, audio, store
        self.conf = Path(conf_dir) / "eq-chain.conf"
        self.pidfile = Path(conf_dir) / "eq-chain.pid"
        self.logfile = Path(conf_dir) / "eq-chain.log"
        self.pipewire, self.pwcli, self.pwdump = pipewire, pwcli, pwdump
        saved = store.load()
        self.bands = {b: float(saved.get("bands", {}).get(b, 0.0)) for b in BANDS}
        self.enabled = bool(saved.get("enabled", False))
        self.target = saved.get("target")
        self._proc = None
        self._node_id = None
        self._lock = threading.RLock()
        self._status = ""
        self._stop = threading.Event()
        self._restoring = False     # the EQ is being put back after a start (the watchdog waits for it)
        if hasattr(audio, "hidden_sinks"):
            audio.hidden_sinks.add(SINK_NAME)

    # ---------------------------------------------------------------- lifecycle
    def available(self):
        if not (shutil.which(self.pipewire) and shutil.which(self.pwcli)):
            return False, "PipeWire tools not found (install pipewire and pipewire-bin)."
        if not module_present():
            return False, "The PipeWire filter-chain module is missing (package libpipewire-0.3-modules)."
        return True, ""

    restore_delay = 2.0     # after login, let the audio server settle before the EQ is put back
    watch_every = 2.0

    def start(self):
        self._kill_stale()
        # restore what the user had before the restart; until then the watchdog leaves the chain alone, so it is
        # started once (two starts would build it twice, the second killing the first: a gap in the sound)
        self._restoring = self.enabled
        threading.Thread(target=self._watchdog, name="eq-watchdog", daemon=True).start()
        if self.enabled:
            threading.Thread(target=self._restore, name="eq-restore", daemon=True).start()

    def stop(self):
        self._stop.set()
        with self._lock:
            if self.enabled and self._running():
                self._restore_default()
            self._kill_chain()

    def _restore(self):
        try:
            if self._stop.wait(self.restore_delay):
                return                          # stopped meanwhile
            with self._lock:
                if not self.enabled or self._running():
                    return                      # switched off meanwhile, or already on
                ok, err = self.enable()
                if not ok:
                    self._status = err
        finally:
            self._restoring = False

    # ---------------------------------------------------------------- process mgmt
    def _running(self):
        return self._proc is not None and self._proc.poll() is None

    def _kill_stale(self):
        """A previous server instance that was SIGKILLed may have left its chain behind."""
        try:
            pid = int(self.pidfile.read_text().strip())
            cmd = Path(f"/proc/{pid}/cmdline").read_bytes().decode(errors="ignore")
            if "eq-chain.conf" in cmd:
                os.kill(pid, 15)
        except (OSError, ValueError):
            pass

    def _kill_chain(self):
        if hasattr(self.audio, "aliases"):
            self.audio.aliases.pop(SINK_NAME, None)
        p, self._proc, self._node_id = self._proc, None, None
        if p is not None and p.poll() is None:
            p.terminate()
            try:
                p.wait(3)
            except subprocess.TimeoutExpired:
                p.kill()
        try:
            self.pidfile.unlink()
        except OSError:
            pass

    def _spawn(self, target):
        if self.r.dry_run:
            self.r.log.append(["spawn", self.pipewire, "-c", str(self.conf), f"target={target}"])
            return True
        self.conf.write_text(chain_conf(target, self.bands), encoding="utf-8")
        self._kill_chain()
        log = open(self.logfile, "ab")
        self._proc = subprocess.Popen([self.pipewire, "-c", str(self.conf)], stdout=log, stderr=log,
                                      env=self.r.env, stdin=subprocess.DEVNULL)
        self.pidfile.write_text(str(self._proc.pid))
        return True

    def _wait_sink(self, timeout=4.0):
        if self.r.dry_run:
            return True
        end = time.time() + timeout
        while time.time() < end:
            if not self._running():
                return False
            if any(s["name"] == SINK_NAME for s in self.audio.outputs(include_hidden=True)):
                return True
            time.sleep(0.15)
        return False

    # ---------------------------------------------------------------- user actions
    def enable(self, target=None):
        with self._lock:
            ok, why = self.available()
            if not ok:
                return False, why
            cur = self.audio.default_name()
            tgt = target or (cur if cur and cur != SINK_NAME else self.target)
            if not tgt or tgt == SINK_NAME:
                return False, "No output device to apply the EQ to."
            if not any(o["name"] == tgt for o in self.audio.outputs(include_hidden=True)):
                return False, "The selected output device isn't available."
            if not self._spawn(tgt) or not self._wait_sink():
                self._kill_chain()
                return False, "The EQ engine didn't start (see eq-chain.log in the config folder)."
            # The EQ sink starts at 100% so loudness is unchanged: the real device keeps its own
            # level, and the app's volume slider then drives the EQ sink.
            self.audio.set_output_volume(SINK_NAME, 100)
            self.audio.set_output_mute(SINK_NAME, False)
            self.audio.set_output(SINK_NAME)
            if hasattr(self.audio, "aliases"):
                self.audio.aliases[SINK_NAME] = tgt   # the UI should name the real device, not the EQ
            self.enabled, self.target = True, tgt
            self._save()
            self._status = ""
            return True, ""

    def disable(self):
        with self._lock:
            self._restore_default()
            self._kill_chain()
            self.enabled = False
            self._save()
            self._status = ""
            return True, ""

    def _restore_default(self):
        if self.target and self.audio.default_name() == SINK_NAME:
            if any(o["name"] == self.target for o in self.audio.outputs(include_hidden=True)):
                self.audio.set_output(self.target)

    def retarget(self, new_output):
        """The user picked another output while the EQ is on: move the EQ in front of it."""
        with self._lock:
            if not self.enabled:
                return self.audio.set_output(new_output)
            self.enable(target=new_output)
            return True

    def set_band(self, band, db):
        if band not in BANDS:
            return False
        db = max(EQ_MIN, min(EQ_MAX, float(db)))
        with self._lock:
            self.bands[band] = db
            self._save()
            if self.enabled and self._running() and not self._apply_live(band, db):
                self.enable(target=self.target)  # fall back to a restart with the new gains
        return True

    def set_preset(self, name):
        gains = PRESETS.get(name)
        if gains is None:
            return False
        for b, v in gains.items():
            self.set_band(b, v)
        return True

    # ---------------------------------------------------------------- live param update
    def _find_node_id(self):
        res = self.r.read([self.pwdump], timeout=5)
        try:
            for obj in json.loads(res.out):
                props = (obj.get("info") or {}).get("props") or {}
                if obj.get("type", "").endswith("Node") and props.get("node.name") == SINK_NAME:
                    return obj["id"]
        except (ValueError, KeyError):
            pass
        return None

    def _apply_live(self, band, db):
        if self.r.dry_run:
            self.r.log.append([self.pwcli, "set-param", "<eq>", "Props", f"{band}:Gain={db}"])
            return True
        if self._node_id is None:
            self._node_id = self._find_node_id()
        if self._node_id is None:
            return False
        params = f'{{ params = [ "{band}:Gain" {float(db)} ] }}'
        res = self.r.write([self.pwcli, "set-param", str(self._node_id), "Props", params])
        if not res.ok:
            self._node_id = None
        return res.ok

    # ---------------------------------------------------------------- state
    def _save(self):
        self.store.merge({"enabled": self.enabled, "bands": self.bands, "target": self.target})

    def _watchdog(self):
        retries = 0
        while not self._stop.wait(self.watch_every):
            with self._lock:
                if not self.enabled or self.r.dry_run or self._restoring:
                    continue
                if not self._running():
                    if retries < 3:
                        retries += 1
                        self._status = "restarting"
                        self.enable(target=self.target)
                    else:
                        self._status = "The EQ engine stopped. Toggle it off and on to retry."
                else:
                    retries = 0

    def snapshot(self):
        ok, why = self.available()
        running = self._running() or (self.r.dry_run and self.enabled)
        default = self.audio.default_name() if ok else None
        bypassed = bool(self.enabled and running and default and default != SINK_NAME)
        status = self._status
        if not status and bypassed:
            status = "Another output is selected, so the EQ is bypassed."
        return {
            "connected": bool(ok),
            "available": bool(ok),
            "reason": why,
            "enabled": self.enabled,
            "running": bool(running),
            "bypassed": bypassed,
            "target": self.target,
            "status": status,
            "level": 0.0,
            "eq": dict(self.bands),
            "routing": {},
            "presets": sorted(PRESETS),
        }
